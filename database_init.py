"""
IMS Database Initializer
-----------------------
Creates the PostgreSQL database, tables, constraints, indexes, trigger
functions, and triggers for the Inventory Management System.

Install:
    pip install psycopg2-binary

Run (PowerShell example):
    $env:PGHOST = "localhost"
    $env:PGPORT = "5432"
    $env:PGUSER = "postgres"
    $env:PGPASSWORD = "your_postgres_password"
    python database_init.py

The database is deliberately created with the exact, case-sensitive name
"IMS_db". PostgreSQL identifiers are case-folded unless quoted.
"""

import os
import sys
import getpass
import psycopg2
from psycopg2 import sql


DB_NAME = "IMS_db"

PG_HOST = os.getenv("PGHOST", "localhost")
PG_PORT = int(os.getenv("PGPORT", "5432"))
PG_USER = os.getenv("PGUSER", "postgres")
PG_PASSWORD = os.getenv("PGPASSWORD") or None
ADMIN_DB = os.getenv("PGADMIN_DB", "postgres")


def get_connection_kwargs(dbname):
    """Return connection settings. Prompt for a password if not supplied."""
    global PG_PASSWORD
    if PG_PASSWORD is None:
        PG_PASSWORD = getpass.getpass(
            f"Password for PostgreSQL user '{PG_USER}': "
        )
    return {
        "host": PG_HOST,
        "port": PG_PORT,
        "user": PG_USER,
        "password": PG_PASSWORD,
        "dbname": dbname,
        "connect_timeout": 10,
    }


def create_database():
    """
    Connect to the maintenance database and create IMS_db if it does not exist.
    CREATE DATABASE must run outside a transaction, so autocommit is enabled.
    """
    print("[1/3] Checking/creating database ...")

    conn = psycopg2.connect(**get_connection_kwargs(ADMIN_DB))
    conn.autocommit = True

    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT 1 FROM pg_database WHERE datname = %s;",
                (DB_NAME,),
            )
            exists = cur.fetchone() is not None

            if exists:
                print(f"      Database {DB_NAME!r} already exists; keeping it.")
            else:
                cur.execute(
                    sql.SQL("CREATE DATABASE {} ENCODING 'UTF8'").format(
                        sql.Identifier(DB_NAME)
                    )
                )
                print(f"      Database {DB_NAME!r} created.")
    finally:
        conn.close()


def create_tables():
    """Create all application tables, constraints, and indexes."""
    print("[2/3] Creating tables and indexes ...")

    ddl = """
    CREATE TABLE IF NOT EXISTS app_user (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name      VARCHAR(100) NOT NULL,
        last_name       VARCHAR(100) NOT NULL,
        user_name       VARCHAR(80) NOT NULL UNIQUE,
        password_hash   TEXT NOT NULL,
        created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS category (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_id       BIGINT NULL,
        name            VARCHAR(100) NOT NULL,
        description     TEXT NULL,

        CONSTRAINT fk_category_parent
            FOREIGN KEY (parent_id)
            REFERENCES category(id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

        CONSTRAINT chk_category_not_own_parent
            CHECK (parent_id IS NULL OR parent_id <> id)
    );

    CREATE TABLE IF NOT EXISTS item (
        id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        item_code       VARCHAR(80) NOT NULL UNIQUE,
        category_id     BIGINT NOT NULL,
        model           VARCHAR(150) NOT NULL,
        size            VARCHAR(50) NULL,
        mounting_type   VARCHAR(10) NULL,
        voltage         VARCHAR(80) NULL,
        material        VARCHAR(100) NULL,
        location        VARCHAR(150) NULL,
        description     TEXT NULL,
        created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

        CONSTRAINT fk_item_category
            FOREIGN KEY (category_id)
            REFERENCES category(id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

        CONSTRAINT chk_item_mounting_type
            CHECK (
                mounting_type IS NULL
                OR mounting_type IN ('SMD', 'DIP')
            )
    );

    CREATE TABLE IF NOT EXISTS inventory (
        id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        item_id             BIGINT NOT NULL UNIQUE,
        quantity            BIGINT NOT NULL DEFAULT 0,
        weighted_avg_cost   NUMERIC(18,4) NULL,
        last_purchase_cost  NUMERIC(18,4) NULL,
        updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

        CONSTRAINT fk_inventory_item
            FOREIGN KEY (item_id)
            REFERENCES item(id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

        CONSTRAINT chk_inventory_quantity
            CHECK (quantity >= 0),

        CONSTRAINT chk_inventory_weighted_avg_cost
            CHECK (weighted_avg_cost IS NULL OR weighted_avg_cost >= 0),

        CONSTRAINT chk_inventory_last_purchase_cost
            CHECK (last_purchase_cost IS NULL OR last_purchase_cost >= 0)
    );

    CREATE TABLE IF NOT EXISTS inventory_transaction (
        id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id                     BIGINT NOT NULL,
        item_id                     BIGINT NOT NULL,
        quantity                    BIGINT NOT NULL,
        transaction_type            VARCHAR(30) NOT NULL,
        price                       NUMERIC(18,4) NULL,
        stock_before                BIGINT NOT NULL,
        stock_after                 BIGINT NOT NULL,
        unit_cost_snapshot          NUMERIC(18,4) NULL,
        transaction_cost_snapshot   NUMERIC(24,4)
            GENERATED ALWAYS AS (
                quantity::NUMERIC * unit_cost_snapshot
            ) STORED,
        created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        description                 TEXT NULL,

        CONSTRAINT fk_transaction_user
            FOREIGN KEY (user_id)
            REFERENCES app_user(id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

        CONSTRAINT fk_transaction_item
            FOREIGN KEY (item_id)
            REFERENCES item(id)
            ON UPDATE RESTRICT
            ON DELETE RESTRICT,

        CONSTRAINT chk_transaction_quantity
            CHECK (quantity > 0),

        CONSTRAINT chk_transaction_type
            CHECK (
                transaction_type IN (
                    'OPENING',
                    'PURCHASE_IN',
                    'OUT',
                    'ADJUSTMENT_IN',
                    'ADJUSTMENT_OUT'
                )
            ),

        CONSTRAINT chk_transaction_price_nonnegative
            CHECK (price IS NULL OR price >= 0),

        CONSTRAINT chk_transaction_snapshot_nonnegative
            CHECK (
                unit_cost_snapshot IS NULL
                OR unit_cost_snapshot >= 0
            ),

        CONSTRAINT chk_transaction_stock_values
            CHECK (stock_before >= 0 AND stock_after >= 0),

        CONSTRAINT chk_transaction_stock_direction
            CHECK (
                (
                    transaction_type IN ('OPENING', 'PURCHASE_IN', 'ADJUSTMENT_IN')
                    AND stock_after = stock_before + quantity
                )
                OR
                (
                    transaction_type IN ('OUT', 'ADJUSTMENT_OUT')
                    AND stock_after = stock_before - quantity
                )
            ),

        CONSTRAINT chk_transaction_price_by_type
            CHECK (
                (transaction_type = 'PURCHASE_IN' AND price IS NOT NULL)
                OR
                (transaction_type IN ('OPENING', 'ADJUSTMENT_IN'))
                OR
                (transaction_type IN ('OUT', 'ADJUSTMENT_OUT') AND price IS NULL)
            )
    );

    CREATE INDEX IF NOT EXISTS idx_item_category_id
        ON item(category_id);

    CREATE INDEX IF NOT EXISTS idx_item_location
        ON item(location);

    CREATE INDEX IF NOT EXISTS idx_transaction_item_created
        ON inventory_transaction(item_id, created_at DESC);

    CREATE INDEX IF NOT EXISTS idx_transaction_user_created
        ON inventory_transaction(user_id, created_at DESC);

    CREATE INDEX IF NOT EXISTS idx_transaction_type_created
        ON inventory_transaction(transaction_type, created_at DESC);
    """

    conn = psycopg2.connect(**get_connection_kwargs(DB_NAME))
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(ddl)
        print("      Tables, constraints, and indexes are ready.")
    finally:
        conn.close()


def create_triggers():
    """Create PostgreSQL trigger functions and attach triggers."""
    print("[3/3] Creating trigger functions and triggers ...")

    ddl = r"""
    /*
     * 1) A newly-created item automatically receives an empty inventory row.
     */
    CREATE OR REPLACE FUNCTION fn_create_inventory_for_item()
    RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
    BEGIN
        INSERT INTO inventory (
            item_id,
            quantity,
            weighted_avg_cost,
            last_purchase_cost
        )
        VALUES (NEW.id, 0, NULL, NULL);

        RETURN NEW;
    END;
    $$;

    DROP TRIGGER IF EXISTS trg_create_inventory_for_item ON item;

    CREATE TRIGGER trg_create_inventory_for_item
    AFTER INSERT ON item
    FOR EACH ROW
    EXECUTE FUNCTION fn_create_inventory_for_item();


    /*
     * 2) Validate a transaction, lock its inventory row, and calculate
     *    stock_before, stock_after, and unit_cost_snapshot.
     *
     * The SELECT ... FOR UPDATE serializes concurrent stock movements
     * for the same item.
     */
    CREATE OR REPLACE FUNCTION fn_prepare_inventory_transaction()
    RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
    DECLARE
        v_quantity       BIGINT;
        v_wac            NUMERIC(18,4);
        v_last_purchase  NUMERIC(18,4);
    BEGIN
        IF NEW.quantity IS NULL OR NEW.quantity <= 0 THEN
            RAISE EXCEPTION 'Transaction quantity must be a positive integer.';
        END IF;

        IF NEW.transaction_type NOT IN (
            'OPENING',
            'PURCHASE_IN',
            'OUT',
            'ADJUSTMENT_IN',
            'ADJUSTMENT_OUT'
        ) THEN
            RAISE EXCEPTION 'Unsupported transaction type: %',
                NEW.transaction_type;
        END IF;

        IF NEW.transaction_type = 'PURCHASE_IN' AND NEW.price IS NULL THEN
            RAISE EXCEPTION 'price is required for PURCHASE_IN.';
        END IF;

        IF NEW.transaction_type IN ('OUT', 'ADJUSTMENT_OUT')
           AND NEW.price IS NOT NULL THEN
            RAISE EXCEPTION
                'price must be NULL for OUT and ADJUSTMENT_OUT; cost is taken from WAC.';
        END IF;

        IF NEW.price IS NOT NULL AND NEW.price < 0 THEN
            RAISE EXCEPTION 'Transaction price cannot be negative.';
        END IF;

        /*
         * The inventory row is created by the item AFTER INSERT trigger.
         * Lock it until the surrounding transaction commits or rolls back.
         */
        SELECT quantity, weighted_avg_cost, last_purchase_cost
          INTO v_quantity, v_wac, v_last_purchase
          FROM inventory
         WHERE item_id = NEW.item_id
         FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION
                'Inventory row not found for item_id %. Create the item first.',
                NEW.item_id;
        END IF;

        NEW.stock_before := v_quantity;

        IF NEW.transaction_type IN ('OPENING', 'PURCHASE_IN', 'ADJUSTMENT_IN') THEN
            NEW.stock_after := v_quantity + NEW.quantity;
        ELSE
            IF v_quantity < NEW.quantity THEN
                RAISE EXCEPTION
                    'Insufficient stock for item_id %. Available: %, requested: %.',
                    NEW.item_id, v_quantity, NEW.quantity;
            END IF;

            NEW.stock_after := v_quantity - NEW.quantity;
        END IF;

        /*
         * Snapshot policy:
         * - Incoming transaction with an explicit price: use that price.
         * - Incoming transaction without a price: use current WAC if known.
         * - Outgoing transaction: use current WAC if known.
         */
        IF NEW.transaction_type IN ('OPENING', 'PURCHASE_IN', 'ADJUSTMENT_IN') THEN
            NEW.unit_cost_snapshot := COALESCE(NEW.price, v_wac);
        ELSE
            NEW.unit_cost_snapshot := v_wac;
        END IF;

        NEW.created_at := COALESCE(NEW.created_at, CURRENT_TIMESTAMP);

        RETURN NEW;
    END;
    $$;

    DROP TRIGGER IF EXISTS trg_prepare_inventory_transaction
        ON inventory_transaction;

    CREATE TRIGGER trg_prepare_inventory_transaction
    BEFORE INSERT ON inventory_transaction
    FOR EACH ROW
    EXECUTE FUNCTION fn_prepare_inventory_transaction();


    /*
     * 3) Apply the inserted transaction to the current inventory balance.
     *    This runs in the same PostgreSQL transaction as the INSERT above.
     */
    CREATE OR REPLACE FUNCTION fn_apply_inventory_transaction()
    RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
    DECLARE
        v_old_wac       NUMERIC(18,4);
        v_new_wac       NUMERIC(18,4);
        v_old_last      NUMERIC(18,4);
        v_new_last      NUMERIC(18,4);
    BEGIN
        SELECT weighted_avg_cost, last_purchase_cost
          INTO v_old_wac, v_old_last
          FROM inventory
         WHERE item_id = NEW.item_id
         FOR UPDATE;

        v_new_wac := v_old_wac;
        v_new_last := v_old_last;

        IF NEW.transaction_type IN ('OPENING', 'PURCHASE_IN', 'ADJUSTMENT_IN') THEN

            IF NEW.price IS NOT NULL THEN
                IF NEW.stock_before = 0 THEN
                    /*
                     * When stock was zero, the incoming priced quantity
                     * establishes the new weighted average.
                     */
                    v_new_wac := NEW.price;

                ELSIF v_old_wac IS NOT NULL THEN
                    /*
                     * Standard weighted-average calculation.
                     */
                    v_new_wac := (
                        (NEW.stock_before::NUMERIC * v_old_wac)
                        + (NEW.quantity::NUMERIC * NEW.price)
                    ) / NEW.stock_after::NUMERIC;

                ELSE
                    /*
                     * Existing stock has unknown value. Do not invent a WAC.
                     */
                    v_new_wac := NULL;
                END IF;
            END IF;

            IF NEW.transaction_type = 'PURCHASE_IN' THEN
                v_new_last := NEW.price;
            END IF;

        END IF;

        /*
         * OUT and ADJUSTMENT_OUT do not change either cost field.
         * If stock reaches zero, WAC is deliberately retained.
         */
        UPDATE inventory
           SET quantity = NEW.stock_after,
               weighted_avg_cost = v_new_wac,
               last_purchase_cost = v_new_last,
               updated_at = CURRENT_TIMESTAMP
         WHERE item_id = NEW.item_id;

        RETURN NEW;
    END;
    $$;

    DROP TRIGGER IF EXISTS trg_apply_inventory_transaction
        ON inventory_transaction;

    CREATE TRIGGER trg_apply_inventory_transaction
    AFTER INSERT ON inventory_transaction
    FOR EACH ROW
    EXECUTE FUNCTION fn_apply_inventory_transaction();


    /*
     * 4) Inventory transactions are immutable.
     *    Corrections must be recorded as new transactions.
     */
    CREATE OR REPLACE FUNCTION fn_prevent_transaction_mutation()
    RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
    BEGIN
        RAISE EXCEPTION
            'Inventory transactions cannot be updated or deleted. '
            'Record a correcting transaction instead.';
    END;
    $$;

    DROP TRIGGER IF EXISTS trg_prevent_transaction_update
        ON inventory_transaction;

    CREATE TRIGGER trg_prevent_transaction_update
    BEFORE UPDATE ON inventory_transaction
    FOR EACH ROW
    EXECUTE FUNCTION fn_prevent_transaction_mutation();

    DROP TRIGGER IF EXISTS trg_prevent_transaction_delete
        ON inventory_transaction;

    CREATE TRIGGER trg_prevent_transaction_delete
    BEFORE DELETE ON inventory_transaction
    FOR EACH ROW
    EXECUTE FUNCTION fn_prevent_transaction_mutation();


    /*
     * 5) Prevent category cycles, e.g. A -> B -> C -> A.
     *    This allows any hierarchy depth; the UI may still show two levels.
     */
    CREATE OR REPLACE FUNCTION fn_validate_category_hierarchy()
    RETURNS TRIGGER
    LANGUAGE plpgsql
    AS $$
    DECLARE
        v_cycle_found BOOLEAN;
    BEGIN
        IF NEW.parent_id IS NULL THEN
            RETURN NEW;
        END IF;

        IF NEW.id IS NOT NULL AND NEW.parent_id = NEW.id THEN
            RAISE EXCEPTION 'A category cannot be its own parent.';
        END IF;

        WITH RECURSIVE ancestors(id, parent_id) AS (
            SELECT c.id, c.parent_id
              FROM category c
             WHERE c.id = NEW.parent_id

            UNION

            SELECT c.id, c.parent_id
              FROM category c
              JOIN ancestors a ON c.id = a.parent_id
        )
        SELECT EXISTS (
            SELECT 1
              FROM ancestors
             WHERE id = NEW.id
        )
        INTO v_cycle_found;

        IF v_cycle_found THEN
            RAISE EXCEPTION
                'Invalid category hierarchy: this change would create a cycle.';
        END IF;

        RETURN NEW;
    END;
    $$;

    DROP TRIGGER IF EXISTS trg_validate_category_hierarchy
        ON category;

    CREATE TRIGGER trg_validate_category_hierarchy
    BEFORE INSERT OR UPDATE OF parent_id ON category
    FOR EACH ROW
    EXECUTE FUNCTION fn_validate_category_hierarchy();
    """

    conn = psycopg2.connect(**get_connection_kwargs(DB_NAME))
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(ddl)
        print("      Trigger functions and triggers are ready.")
    finally:
        conn.close()


def main():
    print("=" * 60)
    print("IMS PostgreSQL Database Initializer")
    print(f"Target database: {DB_NAME}")
    print(f"Server: {PG_HOST}:{PG_PORT}")
    print(f"PostgreSQL user: {PG_USER}")
    print("=" * 60)

    try:
        create_database()
        create_tables()
        create_triggers()

        print("\nDatabase initialization completed successfully.")
        print(f"You can now connect to database {DB_NAME!r}.")
    except psycopg2.Error as exc:
        print("\nDatabase initialization failed.")
        print(f"PostgreSQL error: {exc}", file=sys.stderr)
        sys.exit(1)
    except Exception as exc:
        print("\nDatabase initialization failed.")
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
